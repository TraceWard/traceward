import {test,expect} from '@playwright/test';
const id='11111111-1111-4111-8111-111111111111';
test('JSONL revisions, views, chronology, pagination and evidence survive reopening',async({page,request})=>{
 await page.goto('/');
 await page.locator(`[data-run-id="${id}"]`).click();
 await expect(page.locator('.finding-alert')).toHaveCount(0);
 await page.getByRole('button',{name:'Assessment audit',exact:true}).click();
 await expect(page.locator('.finding-alert')).toHaveAttribute('data-revision','1');
 await request.post('/test/revision/scored');
 await expect(page.locator('.finding-alert')).toHaveAttribute('data-revision','2');
 await page.getByRole('button',{name:'Back to findings',exact:true}).click();
 await expect(page.locator('.finding-tabs button')).toHaveCount(1);
 await expect(page.locator('.score-card')).toContainText('83');
 await expect(page.locator('.score-tag')).toHaveText('SIMULATED EVALUATOR');
 await page.getByText('Inspect exact evaluation packet and typed response').click();
 const audit=await request.get(`/api/runs/${id}/evaluations`);
 const authoritative=(await audit.json()).evaluations;
 expect(JSON.parse(await page.locator('.evaluation-json').innerText())).toEqual(authoritative);
 await page.getByRole('button',{name:'Hooks only',exact:true}).click();
 await expect(page.locator('[data-kind="hook"]')).toHaveCount(1);
 await expect(page.locator('[data-kind="network_send"]')).toHaveCount(0);
 await page.getByRole('button',{name:'Runtime only',exact:true}).click();
 await expect(page.locator('[data-kind="hook"]')).toHaveCount(0);
 await expect(page.locator('[data-kind="network_send"]')).toHaveCount(1);
 await page.getByRole('button',{name:'Processes',exact:true}).click();
 await expect(page.locator('.process-list button')).toHaveCount(2);
 await expect(page.locator('.process-list button').last()).toHaveAttribute('data-depth','1');
 await page.getByRole('button',{name:'Hooks only',exact:true}).click();
 await expect(page.locator('.process-list button')).toHaveCount(0);
 await page.getByRole('button',{name:'Timeline',exact:true}).click();
 await page.getByRole('button',{name:'Combined',exact:true}).click();
 await page.getByLabel('Event type').selectOption('all');
 await page.getByRole('button',{name:'Load earlier events'}).click();
 await expect(page.locator('[data-event-id]')).toHaveCount(306);
 const times=await page.locator('[data-time]').evaluateAll(items=>items.map(i=>Number(i.getAttribute('data-time'))));
 expect(times).toEqual([...times].sort((a,b)=>a-b));
 const ids=await page.locator('[data-event-id]').evaluateAll(items=>items.map(i=>i.getAttribute('data-event-id')));
 expect(new Set(ids).size).toBe(ids.length);
 await page.locator('[data-event-id="shell"]').click();
 await expect(page.locator('.detail-pair')).toContainText(['Evidence ID','Observed at','Source','PID']);
 await page.getByRole('button',{name:'View raw trace excerpt'}).click();
 await expect(page.locator('.raw-modal')).toContainText('metadata');
 await page.locator('.raw-modal .close').click();
 await page.reload();
 await page.locator(`[data-run-id="${id}"]`).click();
 await expect(page.locator('.finding-alert')).toHaveAttribute('data-revision','2');
 await expect(page.locator('.finding-tabs button')).toHaveCount(1);
});
test('unavailable model and collector loss stay visible',async({page,request})=>{
 await request.post('/test/revision/unavailable');
 await page.goto('/');
 await page.locator(`[data-run-id="${id}"]`).click();
 await expect(page.locator('.finding-alert')).toHaveCount(0);
 await page.getByRole('button',{name:'Assessment audit',exact:true}).click();
 await expect(page.locator('.finding-alert')).toHaveAttribute('data-status','inconclusive');
 await expect(page.locator('.model-unavailable')).toContainText('fixture_outage');
 await expect(page.locator('.score-card')).toHaveCount(0);
 await expect(page.locator('body')).toContainText('collector connection lost');
});
test('structured verdict replaces prior content without inventing a score',async({page,request})=>{
 await request.post('/test/revision/structured');
 await page.goto('/');
 await page.locator(`[data-run-id="${id}"]`).click();
 await expect(page.locator('.finding-alert')).toHaveCount(0);
 const findings=await request.get(`/api/runs/${id}/findings`);
 expect((await findings.json()).findings).toEqual([]);
 await page.getByRole('button',{name:'Assessment audit',exact:true}).click();
 await expect(page.locator('.finding-alert')).toHaveAttribute('data-revision','4');
 await expect(page.locator('.finding-tabs button')).toHaveCount(1);
 await expect(page.locator('.structured-assessment')).toContainText('consistent with goal');
 await expect(page.locator('.judge-rationale')).toHaveText('The synthetic goal explicitly requests these fixture operations.');
 await expect(page.locator('.structured-assessment')).toContainText('No numerical risk score');
 await expect(page.locator('.score-bars')).toHaveCount(0);
 await expect(page.locator('.model-unavailable')).toHaveCount(0);
 await page.getByRole('button',{name:'Judge evidence send',exact:true}).click();
 await expect(page.locator('.detail-pair').filter({hasText:'Evidence ID'})).toContainText('send');
 await page.locator('.inspector .panel-head .close').click();
 await page.getByText('Inspect exact evaluation packet and typed response').click();
 const audit=await request.get(`/api/runs/${id}/evaluations`);
 expect(JSON.parse(await page.locator('.evaluation-json').innerText())).toEqual((await audit.json()).evaluations);
 await page.reload();
 await page.locator(`[data-run-id="${id}"]`).click();
 await expect(page.locator('.finding-alert')).toHaveCount(0);
 await page.getByRole('button',{name:'Assessment audit',exact:true}).click();
 await expect(page.locator('.judge-rationale')).toContainText('explicitly requests');
 await expect(page.locator('.assessment-facet')).toHaveCount(6);
 await expect(page.locator('.supported-facts')).toContainText('observed operation');
});
